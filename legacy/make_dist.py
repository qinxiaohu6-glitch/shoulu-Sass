#!/usr/bin/env python3
"""Build a deploy-ready static bundle for Cloudflare Pages.

The project root is *not* safe to upload as-is: it also contains serve.py,
data/ (with the admin token), docs/ and the markdown notes. This script copies
only the files a visitor is allowed to fetch.

Usage:
    python3 make_dist.py

Output: ./dist  — drag that folder into Cloudflare Pages, or run
    npx wrangler pages deploy dist --project-name=dirtool
"""

import os
import shutil

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "dist")

# Directories that contain only public pages.
PAGE_DIRS = ("zh", "tools", "categories", "tags", "makers", "settings")

# Top-level files every deploy needs.
TOP_FILES = ("sitemap.xml", "robots.txt", "llms.txt", "404.html")

# Pages that must never be uploaded: the console has no backend on a static
# host, but there is no reason to hand a scanner its UI either.
SKIP_PAGES = {"admin.html"}

# Cloudflare Pages honours these two files when they sit at the upload root.
HEADERS = """\
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: SAMEORIGIN

/assets/*
  Cache-Control: public, max-age=604800
"""

# robots.txt generated by build.py lists a dynamic sitemap that only serve.py
# can produce. On a static host that URL would 404, so drop the line.
DROP_SITEMAP = "sitemap-reports.xml"


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    copied = 0

    # 1. top-level HTML pages (index.html, tools.html, pricing.html, ...)
    for name in sorted(os.listdir(ROOT)):
        src = os.path.join(ROOT, name)
        if not os.path.isfile(src) or not name.endswith(".html"):
            continue
        if name in SKIP_PAGES:
            continue
        shutil.copy2(src, os.path.join(OUT, name))
        copied += 1

    # 2. whole page trees
    for d in PAGE_DIRS:
        src = os.path.join(ROOT, d)
        if not os.path.isdir(src):
            continue
        shutil.copytree(src, os.path.join(OUT, d))
        for _, _, files in os.walk(src):
            copied += len(files)

    # 3. static assets (css / js / img / fonts)
    shutil.copytree(os.path.join(ROOT, "assets"), os.path.join(OUT, "assets"))
    for _, _, files in os.walk(os.path.join(ROOT, "assets")):
        copied += len(files)

    # 4. crawler-facing text files
    for name in TOP_FILES:
        src = os.path.join(ROOT, name)
        if os.path.isfile(src):
            shutil.copy2(src, os.path.join(OUT, name))
            copied += 1

    # 5. strip the dynamic sitemap line from robots.txt
    robots = os.path.join(OUT, "robots.txt")
    if os.path.isfile(robots):
        with open(robots, encoding="utf-8") as fh:
            lines = fh.readlines()
        kept = [ln for ln in lines if DROP_SITEMAP not in ln]
        if len(kept) != len(lines):
            with open(robots, "w", encoding="utf-8") as fh:
                fh.writelines(kept)
            print("robots.txt: dropped %s line (dynamic only)" % DROP_SITEMAP)

    # 6. Cloudflare Pages headers
    with open(os.path.join(OUT, "_headers"), "w", encoding="utf-8") as fh:
        fh.write(HEADERS)

    # 7. report
    html = sum(1 for _, _, fs in os.walk(OUT) for f in fs if f.endswith(".html"))
    total = sum(len(fs) for _, _, fs in os.walk(OUT))
    size = sum(os.path.getsize(os.path.join(dp, f))
               for dp, _, fs in os.walk(OUT) for f in fs)
    print("dist/ ready: %d files (%d html), %.1f MB"
          % (total, html, size / 1024 / 1024))
    print("upload root: %s" % OUT)


if __name__ == "__main__":
    main()
